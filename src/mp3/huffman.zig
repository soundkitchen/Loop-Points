//! Layer III のハフマン復号(big_values の領域の 2 値の組と、count1 の領域の 4 値の組)。
//!
//! 表は minimp3(https://github.com/lieff/minimp3、CC0 1.0)の `L3_huffman` から取った。
//! 規格(ISO/IEC 11172-3 Table B.7)の符号表を、先読みで引ける木の形に詰めたもの:
//!
//! - big_values の表: 先頭 5 ビットを先読みして `tabs[tab_index[表番号] + 先読み値]` を引く。
//!   値が負なら次の段へ進む(今の段の幅のビットを読み進め、次の段の幅は `値 & 7`、
//!   次の段の開始位置は表の先頭から `-(値 >> 3)`)。0 以上なら葉で、下位 4 ビットが x、
//!   次の 4 ビットが y、`値 >> 8` がその段で読み進めるビット数
//! - count1 の表(A / B): 先頭 4 ビットを先読みして引く。`値 & 8` が 0 なら次の段へ進む
//!   (続く `値 & 3` ビットを足した `(値 >> 3) + 続くビット` を引き直す)。葉の `値 & 7` は符号の長さ、
//!   上位 4 ビット(128 / 64 / 32 / 16)が v / w / x / y
const std = @import("std");
const Reader = @import("bits.zig").Reader;

/// big_values の 1 組を、表 `table` で復号する。linbits と符号まで読み、(x, y) を返す
pub fn decodePair(r: *Reader, table: u5) [2]i32 {
    const base: i32 = tab_index[table];
    var w: u5 = 5;
    var leaf: i32 = tabs[@intCast(base + @as(i32, @intCast(r.peek(w))))];
    while (leaf < 0) {
        r.skip(w);
        w = @intCast(leaf & 7);
        leaf = tabs[@intCast(base + @as(i32, @intCast(r.peek(w))) - (leaf >> 3))];
    }
    r.skip(@intCast(leaf >> 8));
    var out: [2]i32 = undefined;
    const lb = linbits[table];
    for (&out, 0..) |*v, j| {
        var a: u32 = @intCast((leaf >> @intCast(4 * j)) & 15);
        if (a == 15 and lb > 0) a += r.read(lb);
        v.* = @intCast(a);
        if (a != 0 and r.readBool()) v.* = -v.*;
    }
    return out;
}

/// count1 の 1 組(v, w, x, y)を復号する。表 B を使うなら `table_b`。符号まで読む
pub fn decodeQuad(r: *Reader, table_b: bool) [4]i32 {
    const tab: []const u8 = if (table_b) &tab_b else &tab_a;
    var leaf: u32 = tab[r.peek(4)];
    if (leaf & 8 == 0) {
        const n: u5 = @intCast(leaf & 3);
        const next = r.peek(4 + n) & ((@as(u32, 1) << n) - 1);
        leaf = tab[(leaf >> 3) + next];
    }
    r.skip(leaf & 7);
    var out: [4]i32 = undefined;
    for (&out, 0..) |*v, s| {
        if (leaf & (@as(u32, 128) >> @intCast(s)) != 0) {
            v.* = if (r.readBool()) -1 else 1;
        } else {
            v.* = 0;
        }
    }
    return out;
}

