/// 表番号ごとの x / y の値の数(表 0 / 4 / 14 は使わない)
fn tableSize(t: u5) u32 {
    return switch (t) {
        1 => 2,
        2, 3 => 3,
        5, 6 => 4,
        7, 8, 9 => 6,
        10, 11, 12 => 8,
        else => 16,
    };
}

/// 表を木としてたどり、符号の長さの Kraft の和(2^-長さ の合計)と、葉の (x, y) の出現回数を数える
fn walk(table: u5, base: i32, w: u5, prefix_len: u32, kraft: *f64, seen: *[16][16]u32) void {
    const root: i32 = tab_index[table];
    const n = @as(u32, 1) << w;
    var i: u32 = 0;
    while (i < n) : (i += 1) {
        const leaf: i32 = tabs[@intCast(root + base + @as(i32, @intCast(i)))];
        if (leaf < 0) {
            walk(table, -(leaf >> 3), @intCast(leaf & 7), prefix_len + w, kraft, seen);
            continue;
        }
        const len: u5 = @intCast(leaf >> 8);
        // 長さ len の葉は 2^(w - len) 個並ぶので、先頭の 1 つだけ数える
        if (i % (@as(u32, 1) << (w - len)) != 0) continue;
        kraft.* += std.math.ldexp(@as(f64, 1), -@as(i32, @intCast(prefix_len + len)));
        seen[@intCast(leaf & 15)][@intCast((leaf >> 4) & 15)] += 1;
    }
}

test "big_values の表: 符号が完全で、(x, y) がすべて 1 回ずつ現れる" {
    for (1..32) |t| {
        if (t == 4 or t == 14) continue;
        // 16〜23、24〜31 は同じ表を linbits を変えて使う
        var kraft: f64 = 0;
        var seen: [16][16]u32 = @splat(@splat(0));
        walk(@intCast(t), 0, 5, 0, &kraft, &seen);
        try std.testing.expectEqual(1.0, kraft);
        const n = tableSize(@intCast(t));
        for (0..16) |x| for (0..16) |y| {
            try std.testing.expectEqual(@as(u32, if (x < n and y < n) 1 else 0), seen[x][y]);
        };
    }
}

/// `bits`(上位から `len` ビット)を読ませて復号した (x, y)
fn pairOf(table: u5, bits: u32, len: u5) [2]i32 {
    var buf: [4]u8 = undefined;
    std.mem.writeInt(u32, &buf, bits << @intCast(32 - @as(u6, len)), .big);
    var r: Reader = .{ .data = &buf };
    return decodePair(&r, table);
}

test "big_values の表: 規格書の符号" {
    // 表 1: (0,0) = 1、(0,1) = 001、(1,0) = 01、(1,1) = 000(符号ビットは 0 = 正)
    try std.testing.expectEqual([2]i32{ 0, 0 }, pairOf(1, 0b1, 1));
    try std.testing.expectEqual([2]i32{ 0, 1 }, pairOf(1, 0b001_0, 4));
    try std.testing.expectEqual([2]i32{ 1, 0 }, pairOf(1, 0b01_0, 3));
    try std.testing.expectEqual([2]i32{ -1, 1 }, pairOf(1, 0b000_1_0, 5));
    // (0,0) の符号: 表 13 / 16 は 1、表 15 は 111、表 24 は 1111
    try std.testing.expectEqual([2]i32{ 0, 0 }, pairOf(13, 0b1, 1));
    try std.testing.expectEqual([2]i32{ 0, 0 }, pairOf(16, 0b1, 1));
    try std.testing.expectEqual([2]i32{ 0, 0 }, pairOf(15, 0b111, 3));
    try std.testing.expectEqual([2]i32{ 0, 0 }, pairOf(24, 0b1111, 4));
}

test "count1 の表: 6 ビットのどの並びも復号でき、16 通りの符号が完全" {
    for ([_]bool{ false, true }) |table_b| {
        var kraft: f64 = 0;
        var seen: [16]u32 = @splat(0);
        var lens: [16]u32 = @splat(0);
        for (0..64) |bits| {
            const buf = [_]u8{ @intCast(bits << 2), 0, 0, 0 };
            // 復号できる(範囲外を引かない)こと
            var r: Reader = .{ .data = &buf };
            _ = decodeQuad(&r, table_b);
            // 符号の長さと値は、符号ビットを読む前の葉から求める
            var r2: Reader = .{ .data = &buf };
            const tab: []const u8 = if (table_b) &tab_b else &tab_a;
            var leaf: u32 = tab[r2.peek(4)];
            if (leaf & 8 == 0) {
                const n: u5 = @intCast(leaf & 3);
                leaf = tab[(leaf >> 3) + (r2.peek(4 + n) & ((@as(u32, 1) << n) - 1))];
            }
            const len = leaf & 7;
            const value = (leaf >> 4) & 15;
            // 同じ符号(上位 len ビット)の並びは、最初の 1 つだけ数える
            if (bits % (@as(u32, 1) << @intCast(6 - len)) != 0) continue;
            kraft += std.math.ldexp(@as(f64, 1), -@as(i32, @intCast(len)));
            seen[value] += 1;
            lens[value] = len;
        }
        try std.testing.expectEqual(1.0, kraft);
        for (seen) |c| try std.testing.expectEqual(1, c);
        // 表 B はどれも 4 ビット、表 A の (0,0,0,0) は 1 ビット
        if (table_b) {
            for (lens) |l| try std.testing.expectEqual(4, l);
        } else {
            try std.testing.expectEqual(1, lens[0]);
        }
    }
}
